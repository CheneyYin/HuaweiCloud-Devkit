// The OpenCode skills-tree permission seam — pure merge/cleanup logic.
//
// Purpose: direct reads of the devkit skills tree (the taught default load
// path) hit OpenCode's external_directory ask, whose prompt scopes to the
// touched file's own directory and whose "always" grant is session-scoped
// (measured on 1.19.0) — so the installer writes a persistent, directory
// scoped allow for the tree instead, paired with an edit deny so the edit
// tool family cannot silently rewrite server data. Honest semantics, stated
// everywhere the seam is described: the allow covers EVERY path-taking tool
// (bash included — an allowed external directory inherits workspace
// defaults, where bash is allowed), so shell-mediated writes to the tree
// stop asking too; the edit deny governs only the edit/write/patch tools.
// Mitigations: the tree is regenerated by every install/update
// (copyServerPayload), and the PreToolUse hook still denies hcloud writes.
//
// Ownership rules (no receipt, by judgment recorded in the changelog): two
// keys over devkit-only globs — any rule on these globs is devkit-domain by
// construction, so add-only-if-absent (a pre-existing rule with ANY value is
// the user's and survives the write) and value-exact deletion (only the
// devkit-written shapes 'allow'/'deny' are removed at uninstall) are the
// whole contract. The accepted edge: a user-authored same-shape rule that
// predates the seam is removed together with it — pinned by test as
// accepted behavior.
//
// This module is pure: no fs, no spawn, no console — setup-cli.ts owns I/O,
// the version probe, and logging; tests import these functions directly.

// Knowledge boundary, not a feature boundary: 1.19.0 is the only version
// the permission surface has been measured against. Which release
// introduced external_directory is unknown; treat older or unparsable
// versions as unsupported (skip the write) rather than guess.
export const OPENCODE_SEAM_FLOOR = '1.19.0';

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function asRecord(value: unknown): Record<string, unknown> {
  return isRecord(value) ? value : {};
}

// The glob set the seam covers: the plugin-dir skills tree (server data)
// plus per-skill globs for the native core meta-skill copies — per-skill so
// the shared native skills dir, which also holds user skills, is never
// over-granted. Paths are forward-slashed (the mcpPath precedent) so the
// written keys are stable across platforms.
export function skillTreePermissionGlobs(
  pluginSkillsDir: string,
  nativeSkillsDir: string,
  coreSkillNames: readonly string[],
): string[] {
  const norm = (path: string) => path.replace(/\\/g, '/');
  const globs = [`${norm(pluginSkillsDir)}/**`];
  for (const name of [...coreSkillNames].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))) {
    globs.push(`${norm(nativeSkillsDir)}/${name}/**`);
  }
  return globs;
}

export interface SeamApplyResult {
  changed: boolean;
  // Section names whose shape was not an object ('permission' for the
  // top-level whole-config string form, or 'external_directory'/'edit' for
  // scalar-shaped sections): the user owns that shape, the seam skips it.
  skipped: string[];
}

// Mutates config in place. Add-only-if-absent per section: a glob already
// present with ANY value keeps the user's rule; only missing globs get the
// devkit value. Appended keys win under OpenCode's last-matching-rule-wins
// evaluation — deliberate, so the devkit's specific allow beats an earlier
// broader user pattern (e.g. "~/.config/opencode/**": "ask").
export function applySkillTreePermissionSeam(
  config: Record<string, unknown>,
  globs: readonly string[],
): SeamApplyResult {
  if (config.permission !== undefined && !isRecord(config.permission)) {
    // The whole-config string form ("permission": "allow") is the user's
    // global posture; converting it to an object would silently revert
    // every other permission to defaults.
    return { changed: false, skipped: ['permission'] };
  }
  const permission = asRecord(config.permission);
  const skipped: string[] = [];
  let changed = false;
  const sections: Array<readonly [key: string, value: 'allow' | 'deny']> = [
    ['external_directory', 'allow'],
    ['edit', 'deny'],
  ];
  for (const [key, value] of sections) {
    if (permission[key] !== undefined && !isRecord(permission[key])) {
      skipped.push(key);
      continue;
    }
    const section = asRecord(permission[key]);
    const missing = globs.filter((glob) => !Object.hasOwn(section, glob));
    if (missing.length === 0) continue;
    for (const glob of missing) section[glob] = value;
    permission[key] = section;
    changed = true;
  }
  if (changed) config.permission = permission;
  return { changed, skipped };
}

// Mutates config in place. Value-exact deletion only — a user-modified value
// on a devkit glob survives. Sections emptied by OUR deletions are pruned
// (a pre-existing empty section is left untouched), and the permission
// object itself is pruned only when the seam emptied it.
export function removeSkillTreePermissionSeam(config: Record<string, unknown>, globs: readonly string[]): boolean {
  if (!isRecord(config.permission)) return false;
  const permission = asRecord(config.permission);
  let changed = false;
  const sections: Array<readonly [key: string, value: 'allow' | 'deny']> = [
    ['external_directory', 'allow'],
    ['edit', 'deny'],
  ];
  for (const [key, value] of sections) {
    if (!isRecord(permission[key])) continue;
    const section = asRecord(permission[key]);
    let removedHere = false;
    for (const glob of globs) {
      if (section[glob] === value) {
        delete section[glob];
        removedHere = true;
      }
    }
    if (removedHere) {
      changed = true;
      if (Object.keys(section).length === 0) delete permission[key];
    }
  }
  if (changed && Object.keys(permission).length === 0) delete config.permission;
  return changed;
}

// Floor check for the probe result. 2.x parses as supported (an announced
// major must not be classified below-floor by the minor comparison); null
// and unparsable output are unsupported — the caller's polarity is skip.
export function opencodeSeamVersionSupported(version: string | null): boolean {
  if (version === null) return false;
  const match = /^v?(\d+)\.(\d+)\.(\d+)/.exec(version.trim());
  if (!match) return false;
  const major = Number(match[1]);
  const minor = Number(match[2]);
  return major > 1 || (major === 1 && minor >= 19);
}
